#!/usr/bin/env node
// Writes apps/roblox/src/shared/Data.luau: the building and the cast, read from @thick-shift/sim so the Roblox port
// stands in the same rooms as the web game. Run it after changing packages/sim/src (config.ts, map.ts, dressing.ts or
// data.ts):
//
//   node tools/roblox/gen-data.mjs
//
// Index-valued fields (a room, a box, a mascot) stay 0-based, as the web game has them. Luau code adds 1 to look
// one up.
import { writeFileSync } from 'node:fs';
import * as config from '../../packages/sim/src/config.ts';
import { DEAD_TUBES, LAMPS, STAGE } from '../../packages/sim/src/data.ts';
import * as dressing from '../../packages/sim/src/dressing.ts';
import * as map from '../../packages/sim/src/map.ts';

const IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/;
/**
 * @param {unknown} v
 * @param {string} [pad]
 * @returns {string}
 */
function lua(v, pad = '') {
  if (v === null || v === undefined) throw new Error('nil in data');
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new Error('non-finite number');
    return String(v); // shortest round-trip form; Luau reads it back to the same double
  }
  if (typeof v === 'string') return JSON.stringify(v);
  if (typeof v === 'boolean') return String(v);
  const inner = `${pad}\t`;
  if (Array.isArray(v)) {
    if (!v.length) return '{}';
    const flat = v.every(x => typeof x !== 'object' || x === null);
    if (flat) return `{ ${v.map(x => lua(x)).join(', ')} }`;
    return `{\n${v.map(x => `${inner + lua(x, inner)},`).join('\n')}\n${pad}}`;
  }
  // A doorway's `door` back-reference and the like are not data.
  const entries = Object.entries(v).filter(([, x]) => x !== undefined && typeof x !== 'function');
  if (!entries.length) return '{}';
  return `{\n${entries.map(([k, x]) => `${inner + (IDENT.test(k) ? k : `[${JSON.stringify(k)}]`)} = ${lua(x, inner)},`).join('\n')}\n${pad}}`;
}

const data = {
  FINAL_NIGHT: config.FINAL_NIGHT,
  DOORS: config.DOORS,
  MASC: config.MASC,
  PLAYER_R: map.PLAYER_R,
  MASCOT_R: map.MASCOT_R,
  EYE: map.EYE,
  DOOR_H: map.DOOR_H,
  BOOTH: map.BOOTH,
  DUCTS: map.DUCTS,
  ROOMS3: map.ROOMS3,
  DOORWAYS: map.DOORWAYS,
  BOXES: map.BOXES,
  GENERATOR: map.GENERATOR,
  CHARGER: map.CHARGER,
  WALL_MAP: map.WALL_MAP,
  PANELS: map.PANELS,
  BATTERY_SPOTS: map.BATTERY_SPOTS,
  HIDES: map.HIDES,
  REST: map.REST,
  OBSTACLES: map.OBSTACLES,
  EXTRA_NODES: map.EXTRA_NODES,
  FOOT: dressing.FOOT,
  GEN_BACK: dressing.GEN_BACK,
  DRESSING: dressing.DRESSING,
  LAMPS,
  DEAD_TUBES,
  STAGE,
};

const out =
  '--!nocheck\n-- Generated by tools/roblox/gen-data.mjs from the web game. Do not edit by hand.\n' +
  '-- Index-valued fields (rooms, boxes, mascots) are 0-based.\n\nreturn ' +
  lua(data) +
  '\n';
writeFileSync(new URL('../../apps/roblox/src/shared/Data.luau', import.meta.url), out);
console.log('wrote apps/roblox/src/shared/Data.luau', out.length, 'bytes');
